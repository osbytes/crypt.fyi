/**
 * Streaming download worker.
 *
 * Turns a JS-side ReadableStream into a real browser download, so a decrypted
 * payload can be written to disk incrementally instead of being buffered in a
 * tab. Used only where the File System Access API is unavailable — Firefox,
 * Safari, and mobile.
 *
 * ---------------------------------------------------------------------------
 * Scope
 * ---------------------------------------------------------------------------
 * This file MUST be served from /_download/sw.js. A service worker's default
 * scope is the directory of its script, so living here means it can intercept
 * requests under /_download/ and nothing else: not the app shell, not /v/<id>,
 * not any API call. The page that registers it is never placed under its
 * control — only the hidden iframe pointed at /_download/<id> is.
 *
 * The `Service-Worker-Allowed` header, which would widen scope, is
 * deliberately NOT set anywhere. If you ever find yourself adding it, stop.
 *
 * ---------------------------------------------------------------------------
 * Protocol
 * ---------------------------------------------------------------------------
 *   page -> sw   postMessage({ type, id, filename, size, stream }, [stream, port])
 *   sw   -> page port.postMessage({ ok: true })      // armed; safe to navigate
 *   page         <iframe src="/_download/<id>">
 *   sw   -> net  fetch handler answers with the stream as an attachment
 *
 * The ack matters: it confirms the worker is running and holding the stream
 * before the page triggers the navigation, which closes the window where a
 * terminated worker would drop the entry.
 *
 * ---------------------------------------------------------------------------
 * Rules this file lives by
 * ---------------------------------------------------------------------------
 *  - Never touches CacheStorage. Nothing here may write plaintext to disk.
 *  - Never fetches anything. It only answers.
 *  - Handles exactly one URL shape; everything else falls through to network.
 *  - Entries are one-shot and expire.
 *
 * Kept small on purpose: this is security-relevant code in a zero-knowledge
 * app and should be readable end to end in a couple of minutes.
 */

const MESSAGE_TYPE = 'crypt.fyi/download';
const URL_PREFIX = '/_download/';
/** Ids are generated by the page; accept only an opaque, bounded token. */
const ID_PATTERN = /^[A-Za-z0-9_-]{16,64}$/;
/** An armed download the page never collected is dropped after this. */
const ARM_TTL_MS = 5 * 60 * 1000;

/** id -> { filename, size, stream, armedAt } */
const pending = new Map();

self.addEventListener('install', () => {
  // No precaching, no asset list — there is nothing to install.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  // Claim only clients inside /_download/, i.e. the download iframes.
  event.waitUntil(self.clients.claim());
});

const dropExpired = () => {
  const now = Date.now();
  for (const [id, entry] of pending) {
    if (now - entry.armedAt > ARM_TTL_MS) {
      pending.delete(id);
      // Release the producer so the page is not left waiting on a reader that
      // will never arrive.
      void entry.stream.cancel?.('expired').catch(() => {});
    }
  }
};

self.addEventListener('message', (event) => {
  const data = event.data;
  if (!data || data.type !== MESSAGE_TYPE) {
    return;
  }

  // Only same-origin windows may arm a download.
  if (event.origin && event.origin !== self.location.origin) {
    return;
  }

  const port = event.ports && event.ports[0];
  const reject = (reason) => port && port.postMessage({ ok: false, reason });

  if (typeof data.id !== 'string' || !ID_PATTERN.test(data.id)) {
    return reject('invalid id');
  }
  if (!(data.stream instanceof ReadableStream)) {
    return reject('stream is required');
  }
  if (pending.has(data.id)) {
    return reject('id already armed');
  }

  dropExpired();

  pending.set(data.id, {
    filename: typeof data.filename === 'string' ? data.filename : 'download',
    size: Number.isSafeInteger(data.size) && data.size >= 0 ? data.size : undefined,
    stream: data.stream,
    armedAt: Date.now(),
  });

  if (port) {
    port.postMessage({ ok: true });
  }
});

/**
 * Builds a Content-Disposition value.
 *
 * The filename comes from the container's encrypted metadata frame, which is
 * written by whoever created the secret — treat it as hostile input. Strip
 * anything that could break out of the header, then send an ASCII fallback
 * alongside an RFC 5987 encoding for the real name.
 */
const contentDisposition = (rawName) => {
  const name = String(rawName)
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .replace(/[/\\]/g, '_')
    .trim()
    .slice(0, 200);

  const safeName = name || 'download';
  const ascii = safeName.replace(/[^\u0020-\u007e]/g, '_').replace(/["\\]/g, '_');
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(safeName)}`;
};

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Anything that is not a download hand-off is none of this worker's business.
  if (url.origin !== self.location.origin || !url.pathname.startsWith(URL_PREFIX)) {
    return;
  }

  const id = url.pathname.slice(URL_PREFIX.length);
  if (!ID_PATTERN.test(id)) {
    return;
  }

  const entry = pending.get(id);
  if (!entry) {
    // Expired, already collected, or never armed. 404 rather than falling
    // through, so a stale link cannot be answered by the SPA shell.
    event.respondWith(new Response('', { status: 404, headers: { 'Cache-Control': 'no-store' } }));
    return;
  }

  // One-shot: a download URL is never answered twice.
  pending.delete(id);

  const headers = new Headers({
    'Content-Type': 'application/octet-stream',
    'Content-Disposition': contentDisposition(entry.filename),
    'Cache-Control': 'no-store',
    'X-Content-Type-Options': 'nosniff',
  });
  if (entry.size !== undefined) {
    // Lets the browser show real progress and a correct ETA.
    headers.set('Content-Length', String(entry.size));
  }

  event.respondWith(new Response(entry.stream, { status: 200, headers }));
});
